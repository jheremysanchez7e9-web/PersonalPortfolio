const root = document.documentElement;
const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

/* ---------- i18n ---------- */
const langSelect = document.getElementById('lang-select');

function changeLang() {
    const l = langSelect.value;
    const d = dict[l];
    root.lang = l;
    localStorage.setItem('portfolio-lang', l);

    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = d[el.dataset.i18n]; });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', d[el.dataset.i18nAria]); });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        el.placeholder = d[el.dataset.i18nPh];
        el.setAttribute('aria-label', d[el.dataset.i18nPh]);
    });

    startTypewriter(d.roles);
}
langSelect.addEventListener('change', changeLang);

/* ---------- Particle background ---------- */
const canvas = document.getElementById('canvas-bg');
const ctx = canvas.getContext('2d');
let particles = [];
let accent = '';
const mouse = { x: null, y: null, radius: 100 };

window.addEventListener('mousemove', (e) => { mouse.x = e.x; mouse.y = e.y; });
function resizeCanvas() { canvas.width = window.innerWidth; canvas.height = window.innerHeight; }
window.addEventListener('resize', resizeCanvas);
resizeCanvas();

class Particle {
    constructor() {
        this.x = Math.random() * canvas.width;
        this.y = Math.random() * canvas.height;
        this.size = Math.random() * 2 + 1;
        this.vx = (Math.random() - 0.5) * 0.4;
        this.vy = (Math.random() - 0.5) * 0.4;
    }
    draw() {
        ctx.beginPath();
        ctx.arc(this.x, this.y, this.size, 0, Math.PI * 2);
        ctx.fill();
    }
    update() {
        this.x += this.vx; this.y += this.vy;
        if (this.x < 0) this.x = canvas.width; if (this.x > canvas.width) this.x = 0;
        if (this.y < 0) this.y = canvas.height; if (this.y > canvas.height) this.y = 0;
        if (mouse.x === null) return;
        const dx = mouse.x - this.x;
        const dy = mouse.y - this.y;
        const distance = Math.sqrt(dx * dx + dy * dy);
        if (distance > 0 && distance < mouse.radius) {
            this.x -= (dx / distance) * 2;
            this.y -= (dy / distance) * 2;
        }
    }
}

function animate() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    ctx.fillStyle = accent;
    ctx.globalAlpha = 0.4;
    particles.forEach(p => { p.update(); p.draw(); });
    requestAnimationFrame(animate);
}
if (!reducedMotion) {
    for (let i = 0; i < 120; i++) particles.push(new Particle());
    animate();
}

/* ---------- Typewriter ---------- */
let twTime;
function startTypewriter(roles) {
    const el = document.getElementById('typewriter');
    clearTimeout(twTime);
    if (reducedMotion) { el.textContent = roles[0]; return; }
    let rIdx = 0, cIdx = 0, isDel = false;
    function tick() {
        const current = roles[rIdx];
        el.textContent = current.substring(0, cIdx + (isDel ? -1 : 1));
        cIdx += isDel ? -1 : 1;
        let speed = isDel ? 50 : 120;
        if (!isDel && cIdx === current.length) { speed = 2000; isDel = true; }
        else if (isDel && cIdx === 0) { isDel = false; rIdx = (rIdx + 1) % roles.length; speed = 500; }
        twTime = setTimeout(tick, speed);
    }
    tick();
}

/* ---------- Views (driven by the URL hash so links and the back button work) ---------- */
const views = ['home', 'about', 'projects', 'contact'];
function showView() {
    const hash = location.hash.slice(1);
    const id = views.includes(hash) ? hash : 'home';
    document.querySelectorAll('.view-section').forEach(v => { v.hidden = v.id !== id + '-view'; });
    document.querySelectorAll('.nav-link').forEach(l => {
        const on = l.getAttribute('href') === '#' + id;
        l.classList.toggle('active', on);
        if (on) l.setAttribute('aria-current', 'page'); else l.removeAttribute('aria-current');
    });
    document.querySelector('.main-content').scrollTop = 0;
}
window.addEventListener('hashchange', showView);

